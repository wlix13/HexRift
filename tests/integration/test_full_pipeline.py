"""Integration tests using committed fixtures.

Topology:   tests/fixtures/topology.yaml
Keys:       tests/fixtures/keys/{node}.yaml       (real key material, not generated by tests)
Expected:   tests/fixtures/configs/{node}/config.json + haproxy.cfg

Each test rebuilds the config in-memory from the committed topology + keys and
compares byte-for-byte (config.json) or string (haproxy.cfg) against the
committed expected output.  Both inputs and expected outputs are version-controlled,
so any divergence is a genuine rendering regression.

To regenerate expected outputs after an intentional change:
  uv run hexrift --yaml tests/fixtures/topology.yaml build --all --xray --haproxy \\
      --keys-dir tests/fixtures/keys --out-dir tests/fixtures/configs
"""

from pathlib import Path

import orjson
import pytest

from hexrift.app import HexRiftApp
from hexrift.components.render.context import build_exit_context, build_hub_context
from hexrift.components.render.haproxy import render_haproxy
from hexrift.components.render.xray import build_exit_config, build_hub_config, serialize_config
from hexrift.constants import RegionType


FIXTURES_DIR = Path(__file__).parent.parent / "fixtures"
FIXTURE_TOPOLOGY = FIXTURES_DIR / "topology.yaml"
FIXTURE_KEYS_DIR = FIXTURES_DIR / "keys"
FIXTURE_CONFIGS_DIR = FIXTURES_DIR / "configs"

ALL_NODE_IDS = ["nlA00", "mskA00"]


def _build_for_node(node_id: str) -> tuple[bytes, str]:
    """Build xray config bytes + haproxy cfg for a node using committed keys."""

    app = HexRiftApp(yaml_path=FIXTURE_TOPOLOGY)
    region, node = app.schema.get_node(node_id)
    cfg = app.schema.config
    node_keys = app.keys.load_node_keys(node_id, FIXTURE_KEYS_DIR)

    if region.type == RegionType.EXIT:
        hub_nodes = [n for r in cfg.regions if r.type == RegionType.HUB for n in r.nodes]
        ctx = build_exit_context(cfg, region, node, node_keys, hub_nodes)
        xray_config = build_exit_config(ctx)
        haproxy_cfg = render_haproxy(ctx, RegionType.EXIT)
    else:
        exit_node_keys = {
            n.id: app.keys.load_node_keys(n.id, FIXTURE_KEYS_DIR)
            for r in cfg.regions
            if r.type == RegionType.EXIT
            for n in r.nodes
        }
        ctx = build_hub_context(cfg, region, node, node_keys, exit_node_keys)
        xray_config = build_hub_config(ctx)
        haproxy_cfg = render_haproxy(ctx, RegionType.HUB)

    return serialize_config(xray_config), haproxy_cfg


