@pytest.mark.integration
@pytest.mark.parametrize("node_id", ALL_NODE_IDS)
def test_config_json_matches_committed(node_id: str):
    generated, _ = _build_for_node(node_id)
    expected = (FIXTURE_CONFIGS_DIR / node_id / "config.json").read_bytes()
    expected = expected.replace(b"\r\n", b"\n")  # to nullify Windows CRLF
    assert generated == expected, (
        f"config.json mismatch for {node_id!r}.\n"
        "Regenerate with:\n"
        "  uv run hexrift --yaml tests/fixtures/topology.yaml build --all --xray "
        "--keys-dir tests/fixtures/keys --out-dir tests/fixtures/configs"
    )


@pytest.mark.integration
@pytest.mark.parametrize("node_id", ALL_NODE_IDS)
def test_haproxy_cfg_matches_committed(node_id: str):
    _, generated = _build_for_node(node_id)
    expected_bytes = (FIXTURE_CONFIGS_DIR / node_id / "haproxy.cfg").read_bytes()
    expected = expected_bytes.replace(b"\r\n", b"\n").decode()
    generated = generated.replace("\r\n", "\n")
    assert generated == expected, (
        f"haproxy.cfg mismatch for {node_id!r}.\n"
        "Regenerate with:\n"
        "  uv run hexrift --yaml tests/fixtures/topology.yaml build --all --haproxy "
        "--keys-dir tests/fixtures/keys --out-dir tests/fixtures/configs"
    )


@pytest.mark.integration
def test_exit_config_structure():
    generated, _ = _build_for_node("nlA00")
    cfg = orjson.loads(generated)

    # Top-level keys
    for key in ("log", "inbounds", "outbounds", "routing", "dns"):
        assert key in cfg

    # Reality inbound present
    inbound_tags = [ib["tag"] for ib in cfg["inbounds"]]
    assert "direct-xhttp" in inbound_tags

    # CDN inbound present (topology has cdn_xhttp_path for exit region)
    assert "cdn-xhttp" in inbound_tags

    # Standard outbounds present
    outbound_tags = [ob["tag"] for ob in cfg["outbounds"]]
    assert "direct" in outbound_tags
    assert "blocked" in outbound_tags
    assert "warp" in outbound_tags

    # Reality settings use the committed private key
    reality_inbound = next(ib for ib in cfg["inbounds"] if ib["tag"] == "direct-xhttp")
    private_key = reality_inbound["streamSettings"]["realitySettings"]["privateKey"]
    assert private_key == "2M_KKW_6GTmT87r70vuDeqFFmHKy9wmoaADNqUFueGI"

    # Decryption key is ML-KEM-768
    assert reality_inbound["settings"]["decryption"].startswith("mlkem768x25519plus.native.600s.7hyY0")


@pytest.mark.integration
def test_hub_config_structure():
    generated, _ = _build_for_node("mskA00")
    cfg = orjson.loads(generated)

    # No top-level reverse block (reverse is embedded per portal client)
    assert "reverse" not in cfg

    # Hub inbound has clients for all users + server + guests + portal clients
    direct_ib = next(ib for ib in cfg["inbounds"] if ib["tag"] == "direct-xhttp")
    client_emails = [c["email"] for c in direct_ib["settings"]["clients"]]
    assert "alice@test.hexrift" in client_emails
    assert "alice-server@alice" in client_emails
    assert "bob@test.hexrift" in client_emails
    assert "laptop@bob" in client_emails
    assert "phone@bob" in client_emails
    assert "home-portal@alice" in client_emails

    # Portal client carries the reverse tag; no catch-all routing rule for it
    portal_client = next(c for c in direct_ib["settings"]["clients"] if c["email"] == "home-portal@alice")
    assert portal_client.get("reverse") == {"tag": "home-portal"}
    rules = cfg["routing"]["rules"]
    assert not any(r.get("user") == ["home-portal@alice"] for r in rules)

    # CDN inbound only has cdn-access users (alice has cdn, bob does not)
    cdn_ib = next(ib for ib in cfg["inbounds"] if ib["tag"] == "cdn-xhttp")
    cdn_emails = [c["email"] for c in cdn_ib["settings"]["clients"]]
    assert "alice@test.hexrift" in cdn_emails
    assert "bob@test.hexrift" not in cdn_emails

    # Exit outbound present with correct public key
    outbound_tags = [ob["tag"] for ob in cfg["outbounds"]]
    assert "nlA00" in outbound_tags
    nl_outbound = next(ob for ob in cfg["outbounds"] if ob["tag"] == "nlA00")
    pub_key = nl_outbound["streamSettings"]["realitySettings"]["publicKey"]
    assert pub_key == "2SPCC3V_diQ97Pl6CYnFp52St-k7Mof9PNDPS9D4yRU"

    # Hub short IDs from committed groups
    short_ids = direct_ib["streamSettings"]["realitySettings"]["shortIds"]
    assert "aabbccddeeff0011" in short_ids  # main group explicit short_id
    assert "1122334455667788" in short_ids  # guest group explicit short_id

    # Decryption key is X25519
    assert direct_ib["settings"]["decryption"].startswith("mlkem768x25519plus.native.600s.wLmsb")


